const { test, expect } = require('@playwright/test');
const { onboard, go, noOverflow, watchErrors } = require('./helpers.cjs');
for (const width of [360, 390, 430, 768, 1280]) {
  test(`Ruhige Bibliothek ${width}px: Filter, Zurücksetzen, Abbrechen und Menü`, async ({ page }) => {
    const errors = watchErrors(page);
    await page.setViewportSize({ width, height: 844 });
    await onboard(page); await go(page, '#uebungen');
    await expect(page.locator('#lib-grid .drill').first()).toBeVisible();
    await expect(page.locator('#lib-foci')).toBeHidden();
    expect(await page.locator('.lib-head button:visible, .lib-tools button:visible').count()).toBe(3);
    expect(await page.locator('#lib-q').evaluate(e => e.getBoundingClientRect().width)).toBeGreaterThan(150);
    expect(await noOverflow(page)).toBe(true);
    await page.fill('#lib-q','xxxxx');
    await expect(page.locator('#lib-grid .drill')).toHaveCount(0);
    await page.locator('.lib-tools [data-reset]').click();
    await expect(page.locator('#lib-q')).toHaveValue('');
    await page.click('#lib-filter');
    await page.click('[data-scope=new]'); await page.click('[data-tagf=Dribbling]');
    await page.click('[data-fk="1 gegen 1"]');
    await page.click('[data-fapply]');
    await expect(page.locator('#lib-fcount')).toHaveText('3');
    await expect(page.locator('#lib-foci')).toContainText('Neu');
    await expect(page.locator('#lib-foci')).toContainText('Dribbling');
    await expect(page.locator('#lib-grid .drill').first()).toBeVisible();
    await page.click('#lib-filter'); await page.click('[data-scope=own]');
    await page.keyboard.press('Escape');
    await expect(page.locator('dialog[open]')).toHaveCount(0);
    await expect(page.locator('#lib-foci')).toContainText('Neu');
    await page.click('[data-focus-off="1 gegen 1"]');
    await expect(page.locator('#lib-fcount')).toHaveText('2');
    await page.click('[data-reset]');
    await expect(page.locator('#lib-foci')).toBeHidden();
    await page.click('#lib-filter');
    await expect(page.locator('[data-scope=all]')).toHaveAttribute('aria-pressed','true');
    await expect(page.locator('[data-tagf=""]')).toHaveAttribute('aria-pressed','true');
    await page.click('[data-scope=own]'); await page.click('[data-tagf=Dribbling]');
    await page.click('[data-freset]'); await page.click('[data-fapply]');
    await expect(page.locator('#lib-fcount')).toBeHidden();
    await page.click('#lib-more'); await page.click('[data-libview=compact]');
    await page.keyboard.press('Escape');
    await expect(page.locator('dialog[open]')).toHaveCount(0);
    await expect(page.locator('#lib-grid .drill-row').first()).toBeVisible();
    await page.click('#lib-more'); await page.click('#lib-random');
    await expect(page.locator('dialog[open] #d-add')).toBeVisible();
    expect(await noOverflow(page)).toBe(true);
    await page.keyboard.press('Escape');
    await expect(page.locator('dialog[open]')).toHaveCount(0);
    await page.click('#lib-new');
    await expect(page.locator('dialog[open]')).toContainText('Eigene Übung');
    expect(errors).toEqual([]);
  });
}
test('English library: new labels and menu are translated', async({page})=>{
  await page.addInitScript(()=>Object.defineProperty(navigator,'languages',{get:()=>['en-US']}));
  await onboard(page); await go(page,'#uebungen');
  await expect(page.locator('#lib-q')).toHaveAttribute('placeholder','Search exercises');
  await expect(page.locator('#lib-more')).toHaveAttribute('aria-label','More exercise actions');
  await page.click('#lib-more');
  await expect(page.locator('dialog[open] h2')).toHaveText('Exercise actions');
  await expect(page.locator('[data-libview=compact]')).toContainText('Compact list');
});
